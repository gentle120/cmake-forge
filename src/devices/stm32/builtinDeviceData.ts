export function getStm32BuiltinDefinition(series: string, part: string): {
  template: BuiltinDeviceTemplate;
  difference: BuiltinDeviceDifference;
} | undefined {
  const template = stm32BuiltinTemplates[`STM/${series}`];
  if (!template) {
    return undefined;
  }
  return {
    template,
    difference: stm32BuiltinDifferences[part] ?? {}
  };
}
